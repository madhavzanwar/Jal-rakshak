"""Situation-report PDF (reportlab). English only: non-Latin scripts are not embedded."""

from __future__ import annotations

from io import BytesIO
from typing import Any
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from jalrakshak.models import AgentRun, SitRep

FOOTER = "Generated by JalRakshak - decision support only; verify with IMD/CWC"
LEVEL_COLOURS = {"green": "#2e7d32", "yellow": "#f9a825", "orange": "#ef6c00", "red": "#c62828"}


def _p(text: str, style: ParagraphStyle) -> Paragraph:
    return Paragraph(escape(text).replace("\n", "<br/>"), style)


def sitrep_pdf(sitrep: SitRep, run: AgentRun | None = None) -> bytes:
    """Render a SitRep to PDF bytes."""
    buf = BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title=sitrep.title,
        author="JalRakshak",
    )
    ss = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=ss["BodyText"], fontSize=9.5, leading=13)
    h2 = ParagraphStyle(
        "h2",
        parent=ss["Heading2"],
        fontSize=12,
        spaceBefore=8,
        spaceAfter=3,
        textColor=colors.HexColor("#0d47a1"),
    )
    level = run.decision.level if run else "green"
    story: list[object] = [
        _p(sitrep.title, ss["Title"]),
        _p(
            f"Generated {sitrep.generated_at} (UTC) | Run {sitrep.run_id}"
            + (f" | Narrative: {run.llm.provider} / {run.llm.model}" if run else ""),
            ParagraphStyle("meta", parent=body, textColor=colors.grey, fontSize=8),
        ),
        Spacer(1, 4 * mm),
        _p(sitrep.summary, ParagraphStyle("summary", parent=body, fontSize=10.5, leading=14)),
        Spacer(1, 4 * mm),
    ]
    rows = [[_p(k.label, body), _p(k.value, body)] for k in sitrep.key_figures]
    table = Table(rows, colWidths=[60 * mm, 110 * mm])
    table.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#b0bec5")),
                ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#eceff1")),
                ("LINEBEFORE", (0, 0), (0, -1), 4, colors.HexColor(LEVEL_COLOURS[level])),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    story += [table, Spacer(1, 3 * mm)]
    for s in sitrep.sections:
        story += [_p(s.heading, h2), _p(s.body, body)]

    def footer(c: Any, _doc: Any) -> None:
        c.saveState()
        c.setFont("Helvetica", 7.5)
        c.setFillColor(colors.grey)
        c.drawString(18 * mm, 10 * mm, FOOTER)
        c.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {c.getPageNumber()}")
        c.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
